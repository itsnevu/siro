"""Phrase-level English narration matching the active film's visible titles.

Reuse the existing Edge TTS provider and Ava voice. Punctuation, rate and pitch
give each line its own phrasing; final durations are measured, never guessed.
"""
import asyncio
import json
import pathlib
import subprocess
import edge_tts

ROOT = pathlib.Path(__file__).parent
OUT = ROOT / 'public' / 'audio' / 'voice-titles'
PHRASES = [
    ('policy', 'Every move. Within your rules.', '-3%', '+0Hz'),
    ('rules', 'Your rules.', '-5%', '-2Hz'),
    ('strategy', 'Tech Balance. Your idea, structured.', '+2%', '+0Hz'),
    ('built', 'Built around you.', '-5%', '+1Hz'),
    ('limits', 'Always within limits.', '-4%', '-2Hz'),
    ('review', 'Ready for your review.', '-3%', '+1Hz'),
    ('motion', 'In motion.', '-7%', '+0Hz'),
    ('brand', 'Siro.', '-6%', '-2Hz'),
]

async def main():
    OUT.mkdir(parents=True, exist_ok=True)
    semaphore = asyncio.Semaphore(2)
    async def generate(row):
        name, text, rate, pitch = row
        async with semaphore:
            raw = OUT / (name + '-raw.mp3')
            final = OUT / (name + '.wav')
            await edge_tts.Communicate(text, 'en-US-AvaMultilingualNeural', rate=rate, pitch=pitch).save(str(raw))
            subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(raw), '-af',
                'silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.025,areverse,silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.09,areverse,highpass=f=75,loudnorm=I=-16:TP=-2:LRA=7',
                '-ar', '48000', '-ac', '1', str(final)], check=True)
            duration = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', str(final)]))
            raw.unlink()
            result = {'id': name, 'text': text, 'file': 'audio/voice-titles/' + name + '.wav', 'seconds': duration, 'voice': 'en-US-AvaMultilingualNeural', 'rate': rate, 'pitch': pitch}
            print(name, round(duration, 3), 'seconds', flush=True)
            return result
    manifest = await asyncio.gather(*(generate(row) for row in PHRASES))
    (OUT / 'manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    (ROOT / 'src' / 'voice-assets.ts').write_text('// Generated by prepare-title-voice.py.\nexport const VOICE_ASSETS = ' + json.dumps(manifest, indent=2) + ' as const;\n', encoding='utf-8')

asyncio.run(main())
